const fs = require('node:fs/promises');
const path = require('node:path');

const MARKER = '.mycompta-generated';
const SIGNATURE = 'Generated by MyCompta addon:prepare. Do not edit this directory.\n';
const ROOT_FILES = ['app.js', 'server.js', 'package.json', 'package-lock.json'];
const CODE_DIRS = ['google', 'services', 'parsers'];
const PUBLIC_EXTENSIONS = new Set(['.html', '.css', '.js', '.svg', '.png', '.jpg', '.jpeg', '.webp', '.avif', '.ico', '.woff', '.woff2']);

async function prepareAddon(root = path.resolve(__dirname, '..')) {
  root = path.resolve(root);
  const target = path.resolve(root, 'haos', 'mycompta', 'app');
  const relative = path.relative(root, target);
  if (!relative || relative.startsWith('..') || path.isAbsolute(relative)) throw new Error('Destination de préparation invalide.');
  const existing = await fs.lstat(target).catch(error => { if (error.code !== 'ENOENT') throw error; return null; });
  if (existing) {
    if (!existing.isDirectory() || existing.isSymbolicLink()) throw new Error('Le dossier généré ne doit pas être un lien.');
    const signature = await fs.readFile(path.join(target, MARKER), 'utf8').catch(() => '');
    if (signature !== SIGNATURE) throw new Error('Le dossier haos/mycompta/app existe sans marqueur de génération. Déplacez son contenu avant de préparer le paquet.');
    // Resolved, fixed destination beneath this project, protected by its generation marker.
    await fs.rm(target, { recursive: true, force: true });
  }
  await fs.mkdir(target, { recursive: true });
  await fs.writeFile(path.join(target, MARKER), SIGNATURE);
  const files = [];
  async function copyFile(relativeFile) {
    const source = path.join(root, relativeFile);
    const stat = await fs.lstat(source);
    if (!stat.isFile() || stat.isSymbolicLink()) throw new Error(`Fichier source non standard : ${relativeFile}`);
    const destination = path.join(target, relativeFile);
    await fs.mkdir(path.dirname(destination), { recursive: true });
    await fs.copyFile(source, destination);
    files.push(relativeFile.split(path.sep).join('/'));
  }
  async function copyDirectory(relativeDirectory, extensions) {
    const source = path.join(root, relativeDirectory);
    const stat = await fs.lstat(source);
    if (!stat.isDirectory() || stat.isSymbolicLink()) throw new Error(`Dossier source non standard : ${relativeDirectory}`);
    const entries = await fs.readdir(source, { withFileTypes: true });
    for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
      if (entry.name.startsWith('.') || ['node_modules', 'data', 'uploads', 'tests', '__tests__'].includes(entry.name)) continue;
      if (entry.isSymbolicLink()) throw new Error(`Lien symbolique exclu du paquet : ${entry.name}`);
      const relativeFile = path.join(relativeDirectory, entry.name);
      if (entry.isDirectory()) await copyDirectory(relativeFile, extensions);
      else if (extensions.has(path.extname(entry.name).toLowerCase()) && !entry.name.endsWith('.test.js')) await copyFile(relativeFile);
    }
  }
  for (const file of ROOT_FILES) await copyFile(file);
  for (const directory of CODE_DIRS) await copyDirectory(directory, new Set(['.js']));
  await copyDirectory('public', PUBLIC_EXTENSIONS);
  return { target, files };
}

if (require.main === module) prepareAddon().then(({ target, files }) => {
  console.log(`Add-on préparé : ${target} (${files.length} fichiers).`);
  console.log('Copiez haos/mycompta/ vers /addons/mycompta/ ou dans votre dépôt d’add-ons.');
}).catch(error => { console.error(error.message); process.exitCode = 1; });

module.exports = { prepareAddon };
